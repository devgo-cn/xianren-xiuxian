/**
 * src/00-anchor.js —— 锚点表（重构版 v6）
 *
 * ── 这一层解决什么问题 ────────────────────────────────────────────
 * 旧设计把「灵石产出」写成一个闭式公式：
 *
 *   产出/关  inc(s) = INC0 × Gi^s      Gi = G^0.95 ≈ 1.04744
 *   成本/级  cost(L) = BASE × G^L      G  = 1.05
 *
 * 两个都是指数式，于是可以解析反解出「推到第 s 关能买到几级」：
 *
 *   G^L ≈ Gi^s  ⟹  L ≈ 0.95·s
 *
 * ⚠️ 这个 0.95 是公式的【直接输出】，不是调出来的手感值。
 *    实测 15 轮、9000 关，L/s 精确稳定在 0.950，一点都不漂移 ——
 *    玩家会立刻发现「我的等级永远等于关卡数的 95%」，
 *    一眼看穿是算出来的，毫无养成错觉（需求方原话：「太假了」）。
 *
 * ── 手填锚点表：把 L(s) 交回给人 ──────────────────────────────────
 * 根治办法不是继续调 Gi 的指数（那只会把 0.95 挪成别的常数），
 * 而是【不再让公式反解 L】——直接把「推到第 s 关该有多少级」手填成表，
 * 再由表【反推】每关的灵石产出。
 *
 *   玩家看到的是：   第 300 关 ≈ 250 级，第 600 关 ≈ 700 级 ……
 *   游戏内部倒推：   每段需要多少累计灵石，除以段宽 = 该段产量底数
 *
 * 因为锚点是人定的、且各段底数【故意不相等】（1.026 / 1.006 / 1.002 /
 * 0.995 / 0.994 / 0.990 / 0.989 / 0.987 / 0.986），
 * 公式再也无法反推出一个固定比例，比例锁死问题从根上消失。
 *
 * ── 怎么调 ────────────────────────────────────────────────────────
 * 只改 LV_ANCHORS 即可。它是一串 [关卡, 该处应达到的单格等级]。
 * 中间关卡用【对数线性插值】（等级按几何增长，不是等差）。
 *
 * ⚠️ 两条硬约束：
 *   1. 关卡必须严格递增，等级必须非递减（否则会算出负产出）
 *   2. 首项等级不能是 0 —— 反推底数时要做 log，0 会得到 -Infinity
 *      （曾用 [1,0] 当首项，把第一段产量算成 Infinity，已实测复现）
 */

import * as N from './00-num.js';
import * as E from './00-equip.js';

/* ─────────────────────────────────────────────────────────────
 *  ★ 手填锚点表 —— 想调手感只改这里
 * ───────────────────────────────────────────────────────────── */

/**
 * [关卡, 该处玩家单格装备应达到的等级]
 *
 * ── 铺表原则：按【几何】密度，不是等差 ──────────────────────────
 * 实测玩家推进轨迹（每轮重生后的最高关）：
 *   384 → 648 → 1044 → 1439 → 1834 → 2362 → 2889 → 3416 → 4075 → 4734
 *   → 5525 → 6316 → 7106 → 8029 → 8952 → 10006 → 11061 → 12001 → 13360 …
 * 相邻轮倍率稳定在 1.10 ~ 1.22，即关卡是【几何增长】。
 * 所以锚点也必须按几何密度铺（每项约为前项的 1.25~1.3 倍），
 * 否则前期锚点过疏、后期过密，段界台阶会全挤在游戏末期。
 *
 * ⚠️ 别按等差铺（如 300/600/900/1200…）：实测玩家第 5 轮就冲到 1834 关，
 *    等差表在 3000 关以后就完全失效，L/s 会长时间停在同一个值上
 *    （曾出现第 2~8 轮 L/s 恒为 1.1~1.18 的「新平线」，就是锚点不够密）。
 *
 * ── L/s 的设计意图 ──────────────────────────────────────────────
 * 不追求任何常数，而是一条【有起伏的曲线】：
 *   早期略宽松（1.0~1.3）→ 让新玩家连续点几下装备，有爽感
 *   中期回落（0.95~1.0）  → 成本压力显形，开始需要境界支撑
 *   后期收紧（0.85~0.9）  → 逼玩家转生，装备单靠推关吃不满
 * 整体极差约 0.3~0.4，是旧闭式公式（0.002）的百倍以上。
 */
export const LV_ANCHORS = [
  /* 早期：宽松起步，给足正反馈 */
  [1, 5],
  [50, 40],
  [100, 95],
  [200, 210],
  [300, 300],
  [450, 480],
  [600, 660],
  [800, 900],
  /* 中期：小幅领先，玩家感到「越推越顺」 */
  [1000, 1180],
  [1300, 1500],
  [1600, 1820],
  [2000, 2220],
  [2500, 2700],
  [3000, 3150],
  [4000, 4100],
  [5000, 5000],
  /* 后期：开始落后于关卡数，墙显形 */
  [6000, 5900],
  [7000, 6800],
  [8500, 8100],
  [10000, 9300],
  [12000, 10900],
  [14000, 12500],
  [16000, 14000],
  [18000, 15400],
  [20000, 16800],
  [22000, 18100],
  [24000, 19400],
  [26000, 20600],
  [28000, 21700],
  [30000, 22800],
];

/** 表尾之后的关卡沿用最后一个锚点的等级（封顶） */
export const ANCHOR_MAX_STAGE = LV_ANCHORS[LV_ANCHORS.length - 1][0];

/* ─────────────────────────────────────────────────────────────
 *  校验（构建期一次性跑，配错表要立刻炸，不要静默算错）
 * ───────────────────────────────────────────────────────────── */

(function validateAnchors() {
  for (let i = 0; i < LV_ANCHORS.length; i++) {
    const [s, lv] = LV_ANCHORS[i];
    if (!isFinite(s) || !isFinite(lv)) {
      throw new Error('[anchor] 第 ' + i + ' 项不是数字: ' + JSON.stringify(LV_ANCHORS[i]));
    }
    if (lv <= 0) {
      /* ⚠️ 首项等级为 0 会让 log10 得到 -Infinity，反推底数变成 Infinity。
       * 这不是「0 级」的合法表达，0 级请写 0.0001 或直接删掉该项。 */
      throw new Error('[anchor] 第 ' + i + ' 项等级必须 > 0（0 会让底数反解溢出）');
    }
    if (i > 0) {
      const [ps, plv] = LV_ANCHORS[i - 1];
      if (s <= ps) throw new Error('[anchor] 关卡必须严格递增，第 ' + i + ' 项 ' + s + ' <= ' + ps);
      if (lv < plv) throw new Error('[anchor] 等级必须非递减，第 ' + i + ' 项 ' + lv + ' < ' + plv);
    }
  }
  if (LV_ANCHORS[0][0] !== 1) {
    throw new Error('[anchor] 首项关卡必须是 1（否则第 1 关无定义）');
  }
})();

/* ─────────────────────────────────────────────────────────────
 *  查询：第 s 关应达到的等级
 * ───────────────────────────────────────────────────────────── */

/**
 * 第 s 关的锚定等级（对数线性插值，返回原生 Number）。
 *
 * 为什么用【对数】插值而不是线性：
 *   等级曲线本身是几何增长的（成本 1.05^L），若按线性插值，
 *   段内会出现「前松后紧」的突兀折角，玩家能感到速度在段尾突然变慢。
 *   对数插值让段内的相对增长率恒定，手感平滑。
 *
 * @param {number} s 关卡
 * @returns {number} 该关对应的锚定等级
 */
export function levelAt(s) {
  const n = Math.max(1, Math.floor(s));

  const first = LV_ANCHORS[0];
  if (n <= first[0]) return first[1];

  const last = LV_ANCHORS[LV_ANCHORS.length - 1];
  if (n >= last[0]) return last[1];

  for (let i = 0; i < LV_ANCHORS.length - 1; i++) {
    const [s0, l0] = LV_ANCHORS[i];
    const [s1, l1] = LV_ANCHORS[i + 1];
    if (n <= s1) {
      const t = (Math.log(n) - Math.log(s0)) / (Math.log(s1) - Math.log(s0));
      return l0 + (l1 - l0) * t;
    }
  }
  return last[1];
}

/* ─────────────────────────────────────────────────────────────
 *  反推：每关灵石产出
 * ───────────────────────────────────────────────────────────── */

/**
 * 累计到第 s 关、玩家应已获得的灵石总量（大数）。
 *
 * 定义上就等于「买下 levelAt(s) 级所需的累计成本」——
 * 这是整张锚点表的锚定契约：推到第 s 关，刚好买得起锚定的等级。
 *
 * ⚠️ 为什么直接用 upgradeCost 而不是自己再写一遍等比求和：
 *   成本公式已经在 00-equip 里有唯一实现（且已走大数），
 *   这里再写一份就等于有了两个真相源，改 C/COST_GROWTH 时会漏改一处。
 *
 * @param {number} s 关卡
 * @returns {object} 大数
 */
export function cumSpiritAt(s) {
  const L = levelAt(s);
  /* ⚠️ 绝对不要 Math.ceil / Math.round 这个等级！
   * 取整会让「同一个整数等级覆盖的多关」算出完全相同的 cum，
   * 相邻关差分随即变成 0 —— 实测第 299/300/1000 关产出为 0，
   * 第 301 关却突然蹦出 6.25e6，玩家会看到灵石「一顿一顿」地跳。
   * 成本公式 (g^L−1)/(g−1) 对浮点 L 本来就是良定义的，
   * 直接喂连续等级，产出才是平滑的。 */
  return E.costToLevel(L);
}

/**
 * 单关灵石产出：inc(s) = cum(s) − cum(s−1)（大数）
 *
 * ⚠️ 直接用差分而不是「段落底数的几何平均」：
 *   几何平均只在【段内】成立，段界处会有跳变，玩家会看到灵石产量
 *   在 300/600/1000 这些整数关突然蹦一下。差分则天然连续，
 *   段界处的跳变被摊成一条平滑的曲线（因为我们插值本身就是连续的）。
 *
 * @param {number} s 关卡
 * @returns {object} 大数
 */
export function spiritInc(s) {
  const n = Math.max(1, Math.floor(s));
  if (n <= 1) return cumSpiritAt(1);
  return N.sub(cumSpiritAt(n), cumSpiritAt(n - 1));
}

/**
 * 从第 from 关推到第 to 关的累计产出（大数）。
 *
 * 语义与 05-v6.grantSpirit 的半开区间一致：
 *   grantSpirit(from, to) = cum(to) − cum(from)  =  第 from+1 .. to 关
 *
 * @param {number} from
 * @param {number} to
 * @returns {object} 大数
 */
export function spiritBetween(from, to) {
  if (to <= from) return N.ZERO;
  return N.sub(cumSpiritAt(to), cumSpiritAt(from));
}

/* ─────────────────────────────────────────────────────────────
 *  自检 / 调参辅助
 * ───────────────────────────────────────────────────────────── */

/**
 * 导出「关卡 → 等级 → L/s」对照表，调手感时打印出来看。
 * @param {number[]} stages
 * @returns {Array<{stage:number, level:number, ratio:number, cumLog10:number}>}
 */
export function anchorTable(stages) {
  return (stages || LV_ANCHORS.map(a => a[0])).map(s => {
    const lv = levelAt(s);
    const cum = cumSpiritAt(s);
    return {
      stage: s,
      level: Math.round(lv),
      ratio: lv / s,
      cumLog10: N.log10(cum),
    };
  });
}

/**
 * 检查锚点表是否满足「比例不锁死在常数」这一核心设计目标。
 *
 * 判据：L/s 在整条曲线上的极差必须足够大。
 * 旧闭式公式的极差是 0.002（几乎恒定），手填锚点应远超这个数。
 *
 * @returns {{min:number, max:number, spread:number, ok:boolean}}
 */
export function ratioSpread() {
  let lo = Infinity, hi = -Infinity;
  for (const [s] of LV_ANCHORS) {
    if (s < 50) continue;              // 极早期 L/s 无意义（会除以很小的 s）
    const r = levelAt(s) / s;
    if (r < lo) lo = r;
    if (r > hi) hi = r;
  }
  return { min: lo, max: hi, spread: hi - lo, ok: (hi - lo) > 0.05 };
}
